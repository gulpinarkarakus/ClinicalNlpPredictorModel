def temizle(text):

    text = str(text).lower()

    text = re.sub(r"http\S+", "", text)

    text = re.sub(r"\d+", "", text)

    text = re.sub(r"[^a-zçğıöşü\s]", "", text)

    text = re.sub(r"\s+", " ", text).strip()

    return text

